import fs from 'node:fs';
import path from 'node:path';

const root = path.join(process.cwd(), 'public', 'images');
const out = path.join(process.cwd(), 'lib', 'image-manifest.ts');
const valid = new Set(['.png','.jpg','.jpeg','.webp','.avif','.gif','.svg']);
const rows = [];
function walk(dir){
  if(!fs.existsSync(dir)) return;
  for(const name of fs.readdirSync(dir)){
    const full=path.join(dir,name); const st=fs.statSync(full);
    if(st.isDirectory()) walk(full);
    else if(valid.has(path.extname(name).toLowerCase())){
      const rel=path.relative(root,full).replaceAll('\\','/');
      const key=rel.replace(/\.[^.]+$/,'');
      rows.push([key,`/images/${rel}`]);
    }
  }
}
walk(root); rows.sort((a,b)=>a[0].localeCompare(b[0]));
const body=`// AUTO-GENERATED by scripts/generate-image-manifest.mjs\n// Convert/rename images freely, then run: node scripts/generate-image-manifest.mjs\nexport const IMAGE_ASSETS = ${JSON.stringify(Object.fromEntries(rows),null,2)} as const;\nexport type ImageAssetKey = keyof typeof IMAGE_ASSETS;\nexport function imageAsset(key: ImageAssetKey | string){ return (IMAGE_ASSETS as Record<string,string>)[key] || ''; }\n`;
fs.mkdirSync(path.dirname(out),{recursive:true}); fs.writeFileSync(out,body); console.log(`Image manifest: ${rows.length} assets -> ${out}`);
